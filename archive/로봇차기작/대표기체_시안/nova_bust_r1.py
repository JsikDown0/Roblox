def mir(P, i0):
    """P.blocks[i0:] 를 x 대칭으로 복사."""
    for b in list(P.blocks[i0:]):
        P.blocks.append(bm.Block(b.pts * np.array([-1, 1, 1]), b.col, b.mode, b.tol))


def blade(P, root, direc, length, w0, w1, t0, t1, face=(0, -1, 0), col=1, b=0.0):
    """root 에서 direc 방향으로 뻗는 납작한 칼날(폭 w0→w1, 두께 t0→t1). face = 넓은 면이 향하는 쪽."""
    d = np.asarray(direc, float); d /= np.linalg.norm(d)
    n = np.asarray(face, float); n = n - (n @ d) * d; n /= np.linalg.norm(n)
    w = np.cross(d, n)
    r = np.asarray(root, float); tip = r + d * length
    pts = []
    for c, ww, tt in ((r, w0, t0), (tip, w1, t1)):
        for sw in (-1, 1):
            for st in (-1, 1):
                pts.append(c + w * sw * ww / 2 + n * st * tt / 2)
    return P.hull(pts, col, b), (r, d, n, w)


def fin(P, root, direc, L, w0, w1, t0, t1, face, col=1, strip=None):
    blk, (r, d, n, w) = blade(P, root, direc, L, w0, w1, t0, t1, face, col)
    if strip:
        s0, s1, off_w, width, lift = strip
        pts = []
        for s in (s0, s1):
            base = r + d * L * s
            hw = w0 + (w1 - w0) * s
            ht = t0 + (t1 - t0) * s
            for sw in (-1, 1):
                for lt in (ht / 2 - 0.3, ht / 2 + lift):
                    pts.append(base + w * (off_w * hw / 2 + sw * width / 2) + n * lt)
        P.hull(pts, 6).tol = 0.18
    return r, d, n, w


def plate(P, x, y, z, out, seed, n=(2, 1, 2), col=1, gap=1.3, jit=1.3, notch=0.4, step=0.3, tilt=2.0, b=1.3, R=None, about=None):
    """'우둘투둘한' 장갑판 묶음(chunk 기본값)."""
    return P.chunk(x, y, z, col=col, b=b, n=n, gap=gap, out=out, jit=jit, tilt=tilt, seed=seed, notch=notch, step=step,
                   var=0.25, ncol=8, R=R, about=about)


