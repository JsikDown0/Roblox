def build_wing(M):
    P = M.part("WingL", pivot=(32, 36, 92), parent="Torso")
    R = rotx(-12) @ roty(20)
    base = np.array([32.0, 36.0, 90.0])

    def W(pts):
        return [tuple(base + R @ np.asarray(p, float)) for p in pts]

    def wx(z, side):           # 높이 z 에서 날 폭(안쪽 -, 바깥 +)
        return (-9.5 + 0.05 * z) if side < 0 else (9.5 - 0.05 * z)
    segs = [(0, 20), (21.3, 40), (41.3, 60)]
    for k, (z0, z1) in enumerate(segs):
        zi1 = z1 if k < 2 else 53                       # 끝: 바깥 모서리가 높음
        fy = -3.0 - (0.9 if k == 1 else 0.0)
        P.hull(W([(wx(z0, -1), fy, z0), (wx(z0, 1), fy, z0), (wx(z1, -1), fy, zi1), (wx(z1, 1), fy, z1),
                  (wx(z0, -1), 2.6, z0), (wx(z0, 1), 2.6, z0), (wx(z1, -1), 2.6, zi1), (wx(z1, 1), 2.6, z1)]), col=1, b=0.5)
        zm0, zm1 = z0 + 3, z1 - 4
        P.hull(W([(wx(zm0, -1) + 3, fy - 1.3, zm0), (wx(zm0, 1) - 4, fy - 1.3, zm0), (wx(zm1, -1) + 3, fy - 1.3, zm1),
                  (wx(zm1, 1) - 4, fy - 1.3, zm1), (wx(zm0, -1) + 3, fy, zm0), (wx(zm0, 1) - 4, fy, zm0),
                  (wx(zm1, -1) + 3, fy, zm1), (wx(zm1, 1) - 4, fy, zm1)]), col=1, b=0.3)
    # 안쪽 모서리 주황 띠
    P.hull(W([(-10.6, -2.6, 4), (-8.2, -2.6, 4), (-10.6 + 0.05 * 52, -2.6, 52), (-8.2 + 0.05 * 52, -2.6, 52),
              (-10.6, 1.0, 4), (-8.2, 1.0, 4), (-10.6 + 0.05 * 52, 1.0, 52), (-8.2 + 0.05 * 52, 1.0, 52)]), col=6).tol = 0.2
    # 뒤 회색 받침 + 바깥 짙은 띠
    P.hull(W([(-3, 2.4, 0), (4, 2.4, 0), (-3, 2.4, 30), (4, 2.4, 30), (-3, 4.6, 0), (4, 4.6, 0), (-3, 4.6, 26), (4, 4.6, 26)]), col=3, b=0.4)
    P.hull(W([(8.5, -2, 0), (11, -2, 0), (7.5, -2, 36), (10, -2, 36), (8.5, 3, 0), (11, 3, 0), (7.5, 3, 36), (10, 3, 36)]), col=4, b=0.3)
    return P


def build_all():
    M = bm.Model()
    build_torso(M)
    H = build_head(M)
    c = np.array([0.0, -6.0, 84.0])
    for b in H.blocks:
        b.pts = (b.pts - c) * 1.08 + c
    build_shoulder(M)
    M.mirror("ShoulderL", "ShoulderR", parent="Torso")
    M.mirror("ArmL", "ArmR", parent="ShoulderR")
    build_wing(M)
    M.mirror("WingL", "WingR", parent="Torso")
    return M


