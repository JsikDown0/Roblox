import numpy as np

from flag_vox import box, cbox, poly, band

ORANGE, WHITE, FRAME, GLOW = 1, 2, 3, 6


ROOT_TRIM = 205   # 흰 덮깃·뼈대 윗끝(로컬 z). 접으면 바인더 속(로컬 z 200~251)이라 안 보이던 자리 —
                  # 펼치면(55°) 이 자리가 바인더 바깥 못(SpikeL2)을 556칸 뚫었음 [실측: 칸 겹침] → 새 날개는 잘라 냄


def _base(p, G, trim=False):
    """경첩 뭉치 + 뼈대(지금과 같음, trim 이면 뼈대 윗끝을 ROOT_TRIM 까지)."""
    p.add(cbox(G, (24 if trim else 18, 30), (30, 39), (232, 254), {"+zx": 4, "xy": 2}), FRAME)   # trim: 안쪽 6칸 — 펼칠 때 칼자루·백팩을 파고듦
    p.add(box(G, (22, 25), (36, 38), (150, ROOT_TRIM if trim else 236)), FRAME)


def _nozzle(p, G):
    """날개 끝 노즐(10-27 날개 끝 불꽃 자리): 짙은 덩어리 + 아래 끝 발광."""
    X, Y, Z = G
    p.add(cbox(G, (26, 34), (34, 40), (84, 100), {"xy": 2, "+z-x": 3}), FRAME)
    p.add(box(G, (28, 32), (36, 38), (84, 85)), GLOW)


def build_wing(M, kind):
    p = M.parts["WingL"]
    p.a[:] = 0
    G = p.g(); X, Y, Z = G
    if kind == "W0":
        p.add(poly(G, "y", [(28, 250), (50, 262), (50, 140), (28, 86)], rng=(36, 39)), ORANGE)
        p.add(poly(G, "y", [(20, 250), (36, 262), (36, 160), (20, 112)], rng=(33, 35)), WHITE)
        _base(p, G)
    else:
        outer = [(50, 262), (49, 210), (46, 165), (41, 128)]                       # 바깥 변(펼치면 앞전): 뿌리 50 → 끝 쪽 41 테이퍼
        if kind == "W1":
            inner = [(28, 250), (28, 92)]
        else:   # 뒷전 깃 3단: 깃 끝 = (28, 212)·(28, 176)·(28, 140), 홈 꼭짓점은 안쪽으로 7칸·위로 12칸
            inner = [(28, 250), (28, 212), (35, 224), (28, 176), (35, 188), (28, 140), (35, 152), (29, 100)]
        pts = [(30, 92)] + list(reversed(outer)) + inner                         # 끝 → 바깥 변(아래→위) → 안쪽 변(위→아래)
        p.add(poly(G, "y", pts, rng=(36, 39)) & ~((X <= 40) & (Z >= 210) & (Z <= 231)), ORANGE)   # 뿌리 안쪽 홈: 펼칠 때 못(SpikeL2)과 겹치던 자리(접으면 x 35 까진 바인더 속)
        if kind == "W3":   # 흰 덮깃도 깃 3단, 주황 깃보다 반 주기(18칸) 아래로 엇갈려 안쪽으로 비어져 나옴
            wpts = [(36, 262), (36, 150), (24, 120), (20, 128), (27, 158), (20, 164), (27, 194), (20, 200), (27, 230), (20, 236), (20, 250)]
        else:
            wpts = [(20, 250), (36, 262), (36, 160), (20, 112)]
        p.add(poly(G, "y", wpts, rng=(33, 35)) & (Z <= ROOT_TRIM), WHITE)
        _base(p, G, trim=True)
        if kind in ("W1", "W3"):   # 주황 면(뒤, y 39) 가운데 짙은 줄 — 판 긴 축을 따라
            line = band(G, (118, 0, -4.5), (34.5, 0, 128), w=0.6) & (Z >= 118) & (Z <= 246) & (Y == 39)   # 판 가운데 줄 x = 34.5 + (z−128)·0.038
            p.paint(line & (p.a == ORANGE), FRAME)
        _nozzle(p, G)
    M.parts.pop("WingR", None)
    M.mirror("WingL", "WingR", "Backpack")
    return p


