def groove_front(p, m, c, ymax):
    """앞쪽(y <= ymax) 겉면만 한 칸 파고 그 밑을 c 로."""
    G = p.g(); Y = G[1]
    p.groove(np.broadcast_to(m, p.a.shape) & np.broadcast_to(Y <= ymax, p.a.shape), c)


def gface(p, m, c, ax, sgn):
    """ax 축(0 x · 1 y · 2 z) sgn 쪽을 보는 겉면만 m 안에서 한 칸 파고, 바로 안쪽 칸을 c 로(판 위 홈).
    10-29 [실측]: p.groove 는 새로 드러난 안쪽 칸이 m 안에 있어야 칠하는데, 판 겉면에 맞춘 범위(예: 등판 Y >= 10)를
    주면 안쪽 칸이 범위 밖이라 파기만 하고 색이 안 들어갔음 — 허벅지·정강이·정강이 날·팔뚝 초록 0칸."""
    o = p.a > 0
    m = np.broadcast_to(m, p.a.shape)
    P = np.pad(o, 1)
    sl = [slice(1, -1)] * 3
    sl[ax] = slice(1 + sgn, P.shape[ax] - 1 + sgn)
    cut = o & ~P[tuple(sl)] & m                     # 바깥 이웃이 빈 겉면
    p.a[cut] = 0
    inner = np.zeros_like(cut)
    src = [slice(None)] * 3; dst = [slice(None)] * 3
    if sgn > 0: src[ax], dst[ax] = slice(1, None), slice(None, -1)
    else: src[ax], dst[ax] = slice(None, -1), slice(1, None)
    inner[tuple(dst)] = cut[tuple(src)]
    p.a[inner & (p.a > 0)] = c


