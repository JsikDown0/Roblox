# ================================================================== 다리 (3판: 원판 → 다리를 감싸는 갑주 · 발 = Rodin 식 긴 사바톤)
def wrap(G, xc, yc, rx, ry, t, zr, open_dir=None, open_w=0.0):
    """다리를 감싸는 껍데기(위에서 둥근 사각 고리, 두께 t). open_dir = 'front'|'back'|'inner' 쪽을 open_w 폭만큼 비움."""
    X, Y, Z = G
    dx, dy = np.abs(X - xc), np.abs(Y - yc)
    def rr(a, b):                                                       # 모서리 45° 깎은 사각
        return (dx <= a) & (dy <= b) & (dx + dy <= a + b - min(a, b) * 0.45)
    m = rr(rx, ry) & ~rr(rx - t, ry - t) & (Z >= zr[0]) & (Z <= zr[1])
    if open_dir == "front": m &= ~((Y < yc) & (dx <= open_w))
    if open_dir == "back": m &= ~((Y > yc) & (dx <= open_w))
    if open_dir == "inner": m &= ~((X < xc) & (dy <= open_w))
    return m


