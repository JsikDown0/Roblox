def slabpart(M, name, parent, pivot, axis, outline, rng, color, rot=None, pad=3):
    """판 파트: axis 에 수직인 면에 outline 다각형, axis 방향 두께 rng — 세워 만들고 rot 로 기울임(스타일 가이드 1-4)."""
    pts = np.array(outline, float)
    ax = {"x": 0, "y": 1, "z": 2}[axis]; uv = [i for i in range(3) if i != ax]
    lo = [0, 0, 0]; hi = [0, 0, 0]
    lo[ax], hi[ax] = rng[0] - pad, rng[1] + pad + 1
    lo[uv[0]], hi[uv[0]] = int(pts[:, 0].min()) - pad, int(pts[:, 0].max()) + pad + 1
    lo[uv[1]], hi[uv[1]] = int(pts[:, 1].min()) - pad, int(pts[:, 1].max()) + pad + 1
    p = M.part(name, lo, hi, pivot=pivot, parent=parent)
    p.add(poly(p.g(), axis, outline, rng=rng), color)
    if rot is not None: p.rot = rot
    return p


