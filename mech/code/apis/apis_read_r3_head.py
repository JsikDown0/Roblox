def draw(img, parts):
    c = Image.blend(img, Image.new("RGB", img.size, (255, 255, 255)), 0.25)
    ov = Image.new("RGBA", c.size, (0, 0, 0, 0)); d = ImageDraw.Draw(ov)
    for lab, col, g, tp in parts:
        if isinstance(g, tuple) and g[0] == "e":
            _, cx, cy, rx, ry = g; d.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], outline=col + (255,), width=4, fill=col + (35,))
        elif isinstance(g, tuple):
            d.line(g[1], fill=col + (255,), width=7)
        else:
            d.polygon(g, outline=col + (255,), fill=col + (30,), width=4)
    c = Image.alpha_composite(c.convert("RGBA"), ov).convert("RGB"); dt = ImageDraw.Draw(c)
    for lab, col, g, tp in parts:
        w = dt.textlength(lab, font=f); q = (min(max(tp[0], 2), c.width - w - 6), min(max(tp[1], 2), c.height - 28))
        dt.rectangle([q[0] - 3, q[1] - 2, q[0] + w + 3, q[1] + 26], fill=(255, 255, 255), outline=col, width=2)
        dt.text((q[0], q[1] - 1), lab, fill=col, font=f)
    return c


