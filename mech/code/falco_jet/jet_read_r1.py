def panel(box, k, items, title, cx=None):
    x0, y0, x1, y1 = box
    c = im.crop(box).resize(((x1 - x0) * k, (y1 - y0) * k), Image.LANCZOS)
    c = Image.blend(c, Image.new("RGB", c.size, (255, 255, 255)), 0.35)
    d = ImageDraw.Draw(c)
    for gx in range((x0 // 20 + 1) * 20, x1, 20):
        d.line([((gx - x0) * k, 0), ((gx - x0) * k, c.height)], fill=(205, 205, 225))
    for gy in range((y0 // 20 + 1) * 20, y1, 20):
        d.line([(0, (gy - y0) * k), (c.width, (gy - y0) * k)], fill=(205, 205, 225))
    for gx in range((x0 // 100 + 1) * 100, x1, 100):
        d.text(((gx - x0) * k + 2, 2), str(gx), fill=(120, 120, 160), font=F(13))
    for gy in range((y0 // 100 + 1) * 100, y1, 100):
        d.text((2, (gy - y0) * k + 2), str(gy), fill=(120, 120, 160), font=F(13))
    if cx:
        d.line([((cx - x0) * k, 0), ((cx - x0) * k, c.height)], fill=(200, 60, 60), width=1)
    for lab, col, pts, at in items:
        q = [((x - x0) * k, (y - y0) * k) for x, y in pts]
        d.line(q + [q[0]], fill=col, width=3)
        if at:
            d.text(((at[0] - x0) * k, (at[1] - y0) * k), lab, fill=col, font=F(20))
    out = Image.new("RGB", (c.width, c.height + 34), (255, 255, 255))
    out.paste(c, (0, 34)); ImageDraw.Draw(out).text((6, 4), title, fill=(20, 20, 20), font=F(20))
    return out


